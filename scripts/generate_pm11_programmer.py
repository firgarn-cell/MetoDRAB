def set_run_font(run, size=12, bold=False):
    run.font.name = "Times New Roman"
    run._element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")
    run.font.size = Pt(size)
    run.bold = bold


def add_p(doc, text="", *, center=False, bold=False, size=12, after=6, before=0, align=None):
    p = doc.add_paragraph()
    p.paragraph_format.space_after = Pt(after)
    p.paragraph_format.space_before = Pt(before)
    p.paragraph_format.line_spacing = 1.15
    if center:
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    elif align == "left":
        p.alignment = WD_ALIGN_PARAGRAPH.LEFT
    else:
        p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    if text:
        set_run_font(p.add_run(text), size=size, bold=bold)
    return p


def set_cell(cell, text, *, bold=False, center=False, size=9):
    cell.text = ""
    p = cell.paragraphs[0]
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER if center else WD_ALIGN_PARAGRAPH.LEFT
    set_run_font(p.add_run(str(text)), size=size, bold=bold)


def fill(table, rows, header=True):
    for r, row in enumerate(rows):
        for c, val in enumerate(row):
            set_cell(table.rows[r].cells[c], val, bold=header and r == 0, center=True, size=9)


