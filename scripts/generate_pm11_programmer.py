def validate_hours():
    lec = sum(t["lec"] for t in THEMES)
    pr = sum(t["pr"] for t in THEMES)
    self_h = sum(t["self"] for t in THEMES)
    assert lec == TOTALS["lec"], f"lec {lec} != {TOTALS['lec']}"
    assert pr == TOTALS["pr"], f"pr {pr} != {TOTALS['pr']}"
    assert self_h == TOTALS["self"], f"self {self_h} != {TOTALS['self']}"
    by_sem = {}
    for t in THEMES:
        by_sem.setdefault(t["sem"], {"lec": 0, "pr": 0})
        by_sem[t["sem"]]["lec"] += t["lec"]
        by_sem[t["sem"]]["pr"] += t["pr"]
        assert sum(h for h, _ in t["practices"]) == t["pr"], t["title"]
    for sem, exp in MDK_SEMS.items():
        got = by_sem[sem]
        assert got["lec"] == exp["lec"], f"sem{sem} lec {got['lec']}!={exp['lec']}"
        assert got["pr"] == exp["pr"], f"sem{sem} pr {got['pr']}!={exp['pr']}"


